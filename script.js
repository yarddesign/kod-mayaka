function isObject(value) {
  return value !== null &&
    typeof value === "object" &&
    !Array.isArray(value);
}

function cleanMap(value, type) {
  if (!isObject(value)) return {};
  return Object.fromEntries(
    Object.entries(value).filter(([key, item]) =>
      /^[a-z0-9-]+$/i.test(key) && typeof item === type
    )
  );
}

function warnStorage(text) {
  storageWarning.hidden = false;
  storageWarning.textContent = text;
}

function loadState() {
  const fresh = emptyState();

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return fresh;

    const parsed = JSON.parse(raw);
    if (!isObject(parsed) || parsed.version !== 1) {
      throw new Error("Неизвестный формат");
    }

    const storedDone = Array.isArray(parsed.completed)
      ? parsed.completed
      : [];

    // Завершённые уроки должны образовывать непрерывную цепочку.
    for (const lesson of lessons) {
      if (!storedDone.includes(lesson.id)) break;
      fresh.completed.push(lesson.id);
    }

    fresh.review = Array.isArray(parsed.review)
      ? [...new Set(parsed.review.filter(id => lessonIds.includes(id)))]
      : [];

    fresh.answers = cleanMap(parsed.answers, "string");

    for (const field of [
      "solved", "reflection", "assisted", "first", "opened"
    ]) {
      fresh[field] = cleanMap(parsed[field], "boolean");
    }

    if (lessonIds.includes(parsed.current)) {
      fresh.current = parsed.current;
    }

    if (["home", "map", "lesson", "progress", "final"].includes(parsed.view)) {
      fresh.view = parsed.view;
    }

    fresh.finalDone =
      parsed.finalDone === true &&
      fresh.completed.length === lessons.length;

    return fresh;
  } catch (error) {
    warnStorage(
      "Не удалось прочитать сохранённый прогресс. " +
      "Курс открыт с начала. Если браузер запрещает хранение, " +
      "новые результаты сохранятся только до обновления страницы."
    );
    return fresh;
  }
}

