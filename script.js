function prose(text) {
  return `<p class="prose">${escapeHTML(text)}</p>`;
}

function section(title, text, className = "lesson-section") {
  return `<section class="${className}">
    <h2>${escapeHTML(title)}</h2>
    ${prose(text)}
  </section>`;
}

function answerForm(key, task, title) {
  const solved = state.solved[key] === true;
  const message = messages[key];

  const feedback = solved
    ? "Верно! Теперь объясни, почему."
    : message?.text || "";

  const feedbackClass = solved
    ? "correct"
    : message ? "incorrect" : "";

  const question = questionByKey(key);
  const numeric = question.answers.every(answer => /^\d+$/.test(answer));

  return `
    <form class="question" data-question="${key}">
      <h3>${escapeHTML(title)}</h3>
      ${prose(task)}
      <label for="answer-${key}">Твой ответ</label>
      <input
        id="answer-${key}"
        name="answer"
        type="text"
        maxlength="120"
        autocomplete="off"
        ${numeric ? 'inputmode="numeric"' : ""}
        data-answer="${key}"
        value="${escapeHTML(state.answers[key] || "")}"
        aria-describedby="status-${key}"
        placeholder="${numeric ? "Введи число без единиц" : "Введи короткий ответ"}"
      >
      <button type="submit">Проверить ответ</button>
      <p id="status-${key}" class="answer-status ${feedbackClass}"
         role="status" aria-live="polite">${escapeHTML(feedback)}</p>
    </form>`;
}

function helpButton(key, kind, label) {
  const openKey = `${key}-${kind}`;
  const isOpen = state.opened[openKey] === true;

  return `<button type="button"
    data-help="${key}" data-kind="${kind}"
    aria-expanded="${isOpen}"
    aria-controls="help-${openKey}">
    ${isOpen ? "Скрыть: " : ""}${escapeHTML(label)}
  </button>`;
}

function helpBox(key, kind, text) {
  const openKey = `${key}-${kind}`;

  return `<section id="help-${openKey}"
    class="${kind === "hint" ? "tip" : "solution"}"
    ${state.opened[openKey] ? "" : "hidden"}>
    <h3>${kind === "hint" ? "Подсказка" : "Пошаговое решение"}</h3>
    ${prose(text)}
  </section>`;
}

