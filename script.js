function emptyState() {
  return {
    version: 1,
    completed: [],
    current: lessons[0].id,
    view: "home",
    answers: {},
    solved: {},
    reflection: {},
    review: [],
    assisted: {},
    first: {},
    opened: {},
    stats: { completed: 0, total: lessons.length, percent: 0 },
    finalDone: false
  };
}

function isObject(value) {
  return value !== null &&
    typeof value === "object" &&
    !Array.isArray(value);
}

function cleanMap(value, type) {
  if (!isObject(value)) return {};
  return Object.fromEntries(
    Object.entries(value).filter(([key, item]) =>
      /^[a-z0-9-]+$/i.test(key) && typeof item === type
    )
  );
}

function warnStorage(text) {
  storageWarning.hidden = false;
  storageWarning.textContent = text;
}

function loadState() {
  const fresh = emptyState();

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return fresh;

    const parsed = JSON.parse(raw);
    if (!isObject(parsed) || parsed.version !== 1) {
      throw new Error("Неизвестный формат");
    }

    const storedDone = Array.isArray(parsed.completed)
      ? parsed.completed
      : [];

    // Завершённые уроки должны образовывать непрерывную цепочку.
    for (const lesson of lessons) {
      if (!storedDone.includes(lesson.id)) break;
      fresh.completed.push(lesson.id);
    }

    fresh.review = Array.isArray(parsed.review)
      ? [...new Set(parsed.review.filter(id => lessonIds.includes(id)))]
      : [];

    fresh.answers = cleanMap(parsed.answers, "string");

    for (const field of [
      "solved", "reflection", "assisted", "first", "opened"
    ]) {
      fresh[field] = cleanMap(parsed[field], "boolean");
    }

    if (lessonIds.includes(parsed.current)) {
      fresh.current = parsed.current;
    }

    if (["home", "map", "lesson", "progress", "final"].includes(parsed.view)) {
      fresh.view = parsed.view;
    }

    fresh.finalDone =
      parsed.finalDone === true &&
      fresh.completed.length === lessons.length;

    return fresh;
  } catch (error) {
    warnStorage(
      "Не удалось прочитать сохранённый прогресс. " +
      "Курс открыт с начала. Если браузер запрещает хранение, " +
      "новые результаты сохранятся только до обновления страницы."
    );
    return fresh;
  }
}

let state = loadState();

function refreshStats() {
  state.stats = {
    completed: state.completed.length,
    total: lessons.length,
    percent: Math.round(state.completed.length / lessons.length * 100)
  };
}

function saveState() {
  refreshStats();

  if (!storageAvailable) return;

  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (error) {
    storageAvailable = false;
    warnStorage(
      "Браузер не разрешил сохранить прогресс. " +
      "Сейчас курс работает, но после обновления результаты могут исчезнуть. " +
      "Откройте сайт в обычном режиме браузера и разрешите хранение данных."
    );
  }
}

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  }[char]));
}

function normalize(value) {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[.,!?;:]+$/g, "")
    .replace(/\s+/g, " ");
}

function isCorrect(value, allowed) {
  const normalized = normalize(value);
  if (!normalized) return false;

  return allowed.some(answer => {
    const expected = normalize(answer);

    if (/^-?\d+$/.test(expected)) {
      const compact = normalized.replace(/\s/g, "");
      return /^-?\d+$/.test(compact) &&
        Number(compact) === Number(expected);
    }

    return normalized === expected;
  });
}

function isUnlocked(id) {
  const index = lessons.findIndex(lesson => lesson.id === id);
  return index >= 0 &&
    (index === 0 || state.completed.includes(lessons[index - 1].id));
}

function allLessonsDone() {
  return state.completed.length === lessons.length;
}

function addReview(id) {
  if (lessonIds.includes(id) && !state.review.includes(id)) {
    state.review.push(id);
  }
}

function currentLesson() {
  return lessons.find(lesson => lesson.id === state.current) || lessons[0];
}

function questionByKey(key) {
  for (const lesson of lessons) {
    if (key === `l${lesson.id}a`) {
      return {
        key,
        lesson: lesson.id,
        task: lesson.task,
        answers: lesson.answers
      };
    }

    if (key === `l${lesson.id}b`) {
      return {
        key,
        lesson: lesson.id,
        task: lesson.miniTask,
        answers: lesson.miniAnswers
      };
    }
  }

  return diagnostics.find(question => question.key === key) ||
    (key === challenge.key ? challenge : null);
}

function announce(text) {
  notice.textContent = text;
}

function go(view, id) {
  if (view === "lesson") {
    if (!isUnlocked(id)) {
      announce("Сначала заверши предыдущий урок.");
      return;
    }
    state.current = id;
  }

  state.view = view;
  announce("");
  saveState();
  render();

  app.focus();
  window.scrollTo({ top: 0, behavior: "auto" });
}

