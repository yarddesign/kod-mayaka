function checkQuestion(form) {
  const key = form.dataset.question;
  const question = questionByKey(key);
  if (!question) return;

  const input = form.querySelector("input");
  const value = input.value;
  state.answers[key] = value;

  if (!normalize(value)) {
    messages[key] = { text: "Сначала введи ответ. Пустое поле не считается попыткой." };
  } else {
    const correct = isCorrect(value, question.answers);
    state.solved[key] = correct;

    if (!Object.prototype.hasOwnProperty.call(state.first, key)) {
      state.first[key] = correct && !state.assisted[key];
    }

    if (!correct) {
      if (question.lesson) {
        addReview(question.lesson);
      } else if (key === challenge.key) {
        addReview(6);
        addReview(8);
      }

      messages[key] = {
        text: "Пока не совпало. Проверь условие и единицы ответа. Можно открыть подсказку."
      };
    } else {
      delete messages[key];
    }
  }

  saveState();
  const scroll = window.scrollY;
  render();
  window.scrollTo(0, scroll);

  const newInput = document.getElementById(`answer-${key}`);
  if (newInput) newInput.focus({ preventScroll: true });
}

function toggleHelp(key, kind, button) {
  if (!["hint", "solution"].includes(kind)) return;

  const openKey = `${key}-${kind}`;
  const willOpen = !state.opened[openKey];
  state.opened[openKey] = willOpen;

  if (willOpen) {
    const lesson = lessons.find(item => `l${item.id}` === key);

    if (lesson) {
      state.assisted[`l${lesson.id}a`] = true;
      state.assisted[`l${lesson.id}b`] = true;
      addReview(lesson.id);
    } else {
      state.assisted[key] = true;
      const question = questionByKey(key);
      if (question?.lesson) addReview(question.lesson);

      if (key === challenge.key) {
        addReview(6);
        addReview(8);
      }
    }
  }

  saveState();

  const box = document.getElementById(`help-${openKey}`);
  if (box) box.hidden = !willOpen;

  button.setAttribute("aria-expanded", String(willOpen));
  button.textContent =
    (willOpen ? "Скрыть: " : "") +
    (kind === "hint" ? "Подсказка" : "Показать решение");

  if (willOpen) {
    announce("Помощь открыта. Связанные темы добавлены в повторение.");
  }
}

