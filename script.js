function lessonCanFinish(lesson) {
  return state.solved[`l${lesson.id}a`] === true &&
    state.solved[`l${lesson.id}b`] === true &&
    state.reflection[`l${lesson.id}`] === true;
}

function finalCanFinish() {
  return allLessonsDone() &&
    diagnostics.every(question => state.solved[question.key] === true) &&
    state.solved[challenge.key] === true;
}

function syncButtons() {
  const lessonButton = document.getElementById("finish-lesson");

  if (lessonButton) {
    const lesson = currentLesson();
    lessonButton.disabled =
      state.completed.includes(lesson.id) || !lessonCanFinish(lesson);
  }

  const finalButton = document.getElementById("finish-course");

  if (finalButton) {
    finalButton.disabled = state.finalDone || !finalCanFinish();
  }
}

