document.addEventListener("submit", event => {
  const form = event.target.closest("form[data-question]");
  if (!form) return;
  event.preventDefault();
  checkQuestion(form);
});

document.addEventListener("input", event => {
  const input = event.target.closest("[data-answer]");
  if (!input) return;

  const key = input.dataset.answer;
  state.answers[key] = input.value;
  state.solved[key] = false;
  delete messages[key];

  const status = document.getElementById(`status-${key}`);
  if (status) {
    status.textContent = "";
    status.className = "answer-status";
  }

  saveState();
  syncButtons();
});

document.addEventListener("change", event => {
  const checkbox = event.target.closest("[data-reflection]");
  if (!checkbox) return;

  state.reflection[`l${checkbox.dataset.reflection}`] = checkbox.checked;
  saveState();
  syncButtons();
});

document.addEventListener("click", event => {
  const button = event.target.closest("button");
  if (!button || button.disabled) return;

  if (button.dataset.nav) {
    go(button.dataset.nav);
    return;
  }

  if (button.dataset.lesson) {
    go("lesson", Number(button.dataset.lesson));
    return;
  }

  if (button.dataset.help) {
    toggleHelp(button.dataset.help, button.dataset.kind, button);
    return;
  }

  if (button.dataset.review) {
    const id = Number(button.dataset.review);

    if (state.review.includes(id)) {
      state.review = state.review.filter(item => item !== id);
      announce("Тема убрана из повторения.");
    } else {
      addReview(id);
      announce("Тема добавлена в повторение.");
    }

    saveState();
    const scroll = window.scrollY;
    render();
    window.scrollTo(0, scroll);
    return;
  }

  if (button.dataset.finish) {
    const id = Number(button.dataset.finish);
    const lesson = lessons.find(item => item.id === id);

    if (!lesson || !isUnlocked(id) || !lessonCanFinish(lesson)) return;

    if (!state.completed.includes(id)) {
      state.completed.push(id);
    }

    saveState();
    render();
    announce(`Урок завершён! ${lesson.praise}`);
    app.focus();
    window.scrollTo(0, 0);
    return;
  }

  if (button.dataset.action === "start") {
    if (allLessonsDone()) {
      go("final");
    } else {
      const next = lessons.find(item => !state.completed.includes(item.id));
      const current = currentLesson();
      const target = !state.completed.includes(current.id) &&
        isUnlocked(current.id) ? current : next;
      go("lesson", target.id);
    }
    return;
  }

  if (button.dataset.action === "finish-course") {
    if (!finalCanFinish()) return;
    state.finalDone = true;
    saveState();
    render();
    announce("Маяк зажжён! Курс завершён. Ты умеешь искать и объяснять решения.");
    app.focus();
    window.scrollTo(0, 0);
    return;
  }

  if (button.id === "reset") {
    const agreed = window.confirm(
      "Удалить ответы, завершённые уроки и список повторения этого курса? " +
      "Отменить удаление нельзя."
    );

    if (!agreed) return;

    state = emptyState();
    messages = {};
    storageAvailable = true;
    storageWarning.hidden = true;

    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch (error) {
      warnStorage(
        "Не удалось удалить сохранение из хранилища браузера. " +
        "Текущая страница сброшена, но старые данные могут вернуться " +
        "после обновления. Проверьте разрешения на хранение данных."
      );
    }

    render();
    announce("Прогресс сброшен. Можно начать новое приключение.");
    app.focus();
    window.scrollTo(0, 0);
  }
});

